#!/usr/bin/env python3
"""Final-state re-baselined verification of docs/plans/plan-architecture-v5.json (stdlib only).

Part 1: run every plan verify command via Git Bash (PYTHONIOENCODING=utf-8). A command passes if its
        exit code equals expect_exit_code ("match"), or if it mismatches but a mechanical proof shows it
        was superseded by a later task ("superseded"). Exit 0 only if all commands are match/superseded.
Part 2: unplanned-path audit: fileset paths minus union of plan tasks[].changes[].path; every remaining
        path must have a justification (JUSTIFICATIONS below), else the script fails.

Usage: python scripts/verify-final-state.py [--fast] [--write-md]
  --fast      skip cargo/npm commands (dev only; never combined with --write-md)
  --write-md  rewrite the generated section of docs/plans/implementation-status-v5.md (only on success)
"""
import fnmatch
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PLAN = os.path.join(ROOT, "docs", "plans", "plan-architecture-v5.json")
MD = os.path.join(ROOT, "docs", "plans", "implementation-status-v5.md")
BEGIN = "<!-- BEGIN final-state-verification (generated by scripts/verify-final-state.py) -->"
END = "<!-- END final-state-verification -->"
EXPECTED_TOTAL = 181

# Fileset audited in part 2: the committed fileset plus the out-of-plan files added by this verification work.
FILESET_ROOTS = [
    "Cargo.lock", "Cargo.toml", "crates", "src-tauri/Cargo.toml", "src-tauri/capabilities", "src-tauri/src",
    "src/App.tsx", "src/format.ts", "src/types.ts", "docs",
    "scripts", "src/format.test.ts", "tsconfig.json",
]
EXCLUDED_PARTS = {"target", "node_modules", "dist", "__pycache__"}

JUSTIFICATIONS = {
    "Cargo.lock": "generated by cargo (never hand-edited)",
    "crates/lens-core/src/runtime.rs": "v3-origin file carried along by T001's whole-tree git mv; not edited by any planned task (clippy-lint fixes only)",
    "crates/lens-core/src/util.rs": "v3-origin file carried along by T001's whole-tree git mv; not edited by any planned task (clippy-lint fixes only)",
    "docs/architecture*.md": "design documents (inputs to the plan, not code)",
    "docs/specification.md": "design document (input to the plan, not code)",
    "docs/gougi/*": "design review notes (inputs to the plan, not code)",
    "docs/knowledge-kit-usage.md": "knowledge-kit usage doc (tooling, not product code)",
    "docs/implementation-v5.md": "implementation summary doc (mentions verification script and new tests)",
    "docs/plans/implementation-status-v5.md": "status doc (this script generates its final-state section)",
    "docs/plans/plan-architecture-v5.json": "the pinned plan itself (read-only input of this script)",
    "scripts/verify-final-state.py": "this verification script (new, out of plan)",
    "src/format.test.ts": "node:test unit tests for src/format.ts (new, out of plan)",
    "README.md": "user-facing README (new, out of plan)",
    "crates/lens-core/tests/docs_consistency.rs": "mechanical docs/implementation-v5.md vs code/schema check (new, out of plan)",
    "crates/lens-core/src/engine/*": "engine.rs split into submodules by responsibility (behavior-preserving refactor, out of plan)",
    "src-tauri/src/commands.rs": "main.rs split: Tauri command wrappers (behavior-preserving refactor, out of plan)",
    "src-tauri/src/ingest.rs": "main.rs split: ingest thread and event emission (behavior-preserving refactor, out of plan)",
    "src-tauri/src/state.rs": "main.rs split: shared state, lock, settings_dir (behavior-preserving refactor, out of plan)",
    "src-tauri/src/wsl.rs": "main.rs split: parse_ts/wsl_input/NoLaunch and their unit tests (behavior-preserving refactor, out of plan)",
    "tsconfig.json": "excludes src/**/*.test.ts from tsc (no node types in project)",
}


def find_bash():
    cands = [os.environ.get("GIT_BASH", ""), r"C:\Program Files\Git\bin\bash.exe", r"C:\Program Files\Git\usr\bin\bash.exe"]
    for c in cands:
        if c and os.path.exists(c):
            return c
    return shutil.which("bash") or "bash"


BASH = find_bash()


def run_bash(cmd, timeout=1800):
    env = dict(os.environ, PYTHONIOENCODING="utf-8")
    p = subprocess.run([BASH, "-c", cmd], cwd=ROOT, env=env, stdin=subprocess.DEVNULL,
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT, timeout=timeout)
    return p.returncode, p.stdout


def sha(b):
    return hashlib.sha256(b).hexdigest()


# Files split out of a planned file by the behavior-preserving refactor: ownership follows the origin file.
SPLIT_ORIGIN = {
    "src-tauri/src/commands.rs": "src-tauri/src/main.rs",
    "src-tauri/src/ingest.rs": "src-tauri/src/main.rs",
    "src-tauri/src/state.rs": "src-tauri/src/main.rs",
    "src-tauri/src/wsl.rs": "src-tauri/src/main.rs",
}


def owners(path, tasks, after_idx):
    path = SPLIT_ORIGIN.get(path, path)
    """Later tasks (index > after_idx) whose changes[] claim path (exact or directory prefix)."""
    out = []
    for j in range(after_idx + 1, len(tasks)):
        for c in tasks[j]["changes"]:
            p = c["path"].rstrip("/")
            if path == p or path.startswith(p + "/"):
                out.append(tasks[j]["id"])
                break
    return out


def proof_rg(cmd, tasks, idx):
    """Same rg now matches (exit 0) and every matching file is owned by a later task."""
    pcmd = re.sub(r"^rg ", "rg --sort path --with-filename ", cmd, count=1)
    code, out = run_bash(pcmd)
    if code != 0:
        return False, out, f"proof rg exit {code} (expected 0)"
    paths = []
    for line in out.decode("utf-8", "replace").splitlines():
        m = re.match(r"^(.+?):(\d+):", line)
        if m:
            paths.append((m.group(1).replace("\\", "/"), int(m.group(2))))
    if not paths:
        return False, out, "no file:line parsed from rg output"
    unowned = sorted({p for p, _ in paths if not owners(p, tasks, idx)})
    if unowned:
        return False, out, "matches not owned by a later task: " + ",".join(unowned)
    first = paths[0]
    ev = f"{len(paths)} hit(s); first {first[0]}:{first[1]} owned by {','.join(owners(first[0], tasks, idx))}"
    return True, out, ev


def proof_t001_lib(tasks):
    code, out = run_bash("cargo metadata --format-version 1 --no-deps")
    if code != 0:
        return False, out, "cargo metadata failed"
    meta = json.loads(out.decode("utf-8", "replace"))
    pkg = next((p for p in meta["packages"] if p["name"] == "lens-core"), None)
    libs = [t["name"] for t in pkg["targets"] if "lib" in t["kind"]] if pkg else []
    t002 = next(t for t in tasks if t["id"] == "T002")
    claims = any(c["path"] == "crates/lens-core/Cargo.toml" for c in t002["changes"])
    ok = libs == ["lens_core"] and claims
    text = json.dumps({"libTargets": libs, "T002ClaimsManifest": claims}).encode()
    return ok, text, f"lib target(s) {libs} per cargo metadata; T002 changes crates/lens-core/Cargo.toml: {claims}"


def proof_t032_handlers(tasks):
    src = open(os.path.join(ROOT, "src-tauri", "src", "main.rs"), encoding="utf-8").read()
    m = re.search(r"generate_handler!\[([^\]]*)\]", src)
    names = [n.strip() for n in m.group(1).split(",") if n.strip()] if m else []
    t033 = next(t for t in tasks if t["id"] == "T033")
    claims = any(c["path"] == "src-tauri/src/main.rs" and "get_snapshot" in c.get("note", "") for c in t033["changes"])
    ok = len(names) == 5 and "get_snapshot" not in src and claims
    text = json.dumps({"handlers": names, "T033RemovesGetSnapshot": claims}).encode()
    return ok, text, f"generate_handler has {len(names)} commands ({','.join(names)}), no get_snapshot; T033 claims the removal: {claims}"


def part1(tasks, fast):
    total = matched = 0
    sup = []
    failures = []
    heavy = re.compile(r"^(cargo|npm|test \"\$\(cargo)")
    for i, t in enumerate(tasks):
        for n, v in enumerate(t["verify"], 1):
            total += 1
            cmd = v["command"]
            if fast and heavy.match(cmd):
                matched += 1
                continue
            code, out = run_bash(cmd)
            if code == v["expect_exit_code"]:
                matched += 1
                continue
            if t["id"] == "T001" and cmd.startswith("cargo metadata"):
                ok, pout, ev = proof_t001_lib(tasks)
                kind = "cargo metadata lib name"
            elif t["id"] == "T032" and "generate_handler" in cmd:
                ok, pout, ev = proof_t032_handlers(tasks)
                kind = "generate_handler set"
            elif cmd.startswith("rg ") and v["expect_exit_code"] == 1 and code == 0:
                ok, pout, ev = proof_rg(cmd, tasks, i)
                kind = "rg matches now; owned by later task"
            else:
                ok, pout, ev, kind = False, out, f"no supersession rule (exit {code}, expected {v['expect_exit_code']})", "none"
            if ok:
                sup.append(dict(task=t["id"], n=n, cmd=cmd, expect=v["expect_exit_code"], got=code,
                                kind=kind, proof_exit=0, sha=sha(pout), evidence=ev))
            else:
                failures.append(f"{t['id']}#{n}: {ev}: {cmd[:120]}")
    return total, matched, sup, failures


def walk_fileset():
    files = set()
    for r in FILESET_ROOTS:
        full = os.path.join(ROOT, r)
        if os.path.isfile(full):
            files.add(r)
        elif os.path.isdir(full):
            for d, dirs, fs in os.walk(full):
                dirs[:] = [x for x in dirs if x not in EXCLUDED_PARTS]
                for f in fs:
                    files.add(os.path.relpath(os.path.join(d, f), ROOT).replace("\\", "/"))
    return files


def justify(path):
    for pat, why in JUSTIFICATIONS.items():
        if path == pat or fnmatch.fnmatch(path, pat):
            return why
    return None


def part2(tasks):
    planned = [c["path"].rstrip("/") for t in tasks for c in t["changes"]]
    fileset = walk_fileset()
    rest = sorted(f for f in fileset if not any(f == p or f.startswith(p + "/") for p in planned))
    rows = [(f, justify(f)) for f in rest]
    bad = [f for f, w in rows if w is None]
    return len(fileset), len(set(planned)), rows, bad


def render_md(total, matched, sup, nfiles, nplanned, rows):
    L = [BEGIN, "", "## Final-state re-baselined verification", "",
         "Generated by `python scripts/verify-final-state.py --write-md` (stdlib only; plan commands run via Git Bash with `PYTHONIOENCODING=utf-8`). "
         "The pinned plan JSON is untouched. A command passes if its exit code equals the planned one (match) or it mismatches but a mechanical proof shows a later task superseded it (superseded). "
         "Script exit code at generation: **0**.", "",
         f"Totals: {total} commands, {matched} match, {len(sup)} superseded-with-proof, 0 unexplained.", "",
         "Proof rules: `rg` checks = the same rg (run with `--sort path --with-filename`) now exits 0 and every matching file is claimed by a later task's `changes[]`; "
         "T001 lib check = `cargo metadata` lib target is `lens_core` (T002 removed the alias); T032 handler check = `generate_handler!` has exactly 5 commands without `get_snapshot` (T033 removed it). "
         "sha256 is over the proof assertion output (sorted, deterministic). Proof exit is 0 for every row.", "",
         "| Task | # | Exit (planned -> now) | Proof | Proof exit | Proof output sha256 | Evidence |", "|---|---|---|---|---|---|---|"]
    for s in sup:
        L.append(f"| {s['task']} | {s['n']} | {s['expect']} -> {s['got']} | {s['kind']} | {s['proof_exit']} | `{s['sha']}` | {s['evidence']} |")
    L += ["", "## Unplanned path-set comparison", "",
          f"Fileset ({nfiles} files, excluding target/, node_modules/, dist/) minus the union of plan `tasks[].changes[].path` ({nplanned} distinct paths) leaves {len(rows)} path(s); "
          "the script fails if any lacks a justification.", "", "| Path | Justification |", "|---|---|"]
    for f, w in rows:
        L.append(f"| `{f}` | {w} |")
    L += ["", END, ""]
    return "\n".join(L)


def write_md(section):
    s = open(MD, encoding="utf-8").read()
    if BEGIN in s and END in s:
        a = s.index(BEGIN)
        b = s.index(END) + len(END)
        s = s[:a].rstrip("\n") + "\n\n" + section + s[b:].lstrip("\n")
    else:
        s = s.rstrip("\n") + "\n\n" + section
    open(MD, "w", encoding="utf-8", newline="\n").write(s)


def main():
    fast = "--fast" in sys.argv
    plan = json.load(open(PLAN, encoding="utf-8"))
    tasks = plan["tasks"]
    total, matched, sup, failures = part1(tasks, fast)
    nfiles, nplanned, rows, bad = part2(tasks)
    print(f"part1: {total} commands, {matched} match, {len(sup)} superseded-with-proof, {len(failures)} failing")
    for s in sup:
        print(f"  superseded {s['task']}#{s['n']} [{s['kind']}] sha256={s['sha']} :: {s['evidence']}")
    for f in failures:
        print("  FAIL", f)
    print(f"part2: fileset {nfiles}, planned {nplanned}, unplanned {len(rows)}, unjustified {len(bad)}")
    for f, w in rows:
        print(f"  {'OK  ' if w else 'FAIL'} {f} :: {w}")
    ok = not failures and not bad and total == EXPECTED_TOTAL
    if total != EXPECTED_TOTAL:
        print(f"FAIL: expected {EXPECTED_TOTAL} commands, found {total}")
    if ok and "--write-md" in sys.argv and not fast:
        write_md(render_md(total, matched, sup, nfiles, nplanned, rows))
        print("wrote", MD)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
